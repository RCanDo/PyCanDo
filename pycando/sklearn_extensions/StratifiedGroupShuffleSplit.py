from typing import Generator

import numpy as np
import pandas as pd


class StratifiedGroupShuffleSplit(object):
    """
    This is primitive version of stratified grouped shuffle split:

    1. Only binary, 0-1 valued target `y` is considered;
    more precisely, all values different from 1 are considered as one class, say non-1,
    hence one may pass whatever variable it likes but the algorithm only distinguishes values 1 and non-1.

    2. Splits are made wrt. unique group values, i.e.
    `test_size` proportion is applied to number of unique values of a group variable.
    Doing it wrt. the exact number of observations (records) is much more problematic and rather less useful.

    3. Stratification is also done wrt unique group values, i.e.
    for a given unique group value if there is at least one observation within this group where `y = 1`
    then it is considered that `y = 1` for the whole group.
    Thus each unique group value is unambiguously ascribed to one of `y = 1` class or "y != 1" class.
    Then from each of these classes the `test_size` portion of unique group values is randomly chosen
    and put into "test" portion of the data.
    The rest is "train" portion of unique group values thus consists of `1 - test_size` unique group values
    from each of the `y = 1` class or "y != 1" class.
    
    Terminology
    -----------
    ShuffleSplit...             –  split generator factory  class
    cv = ShuffleSplit...(n_splits=2, test_size=0.5, random_state=0)  –  split generator factory  instance
    cv.split                    –  split generator function
    cv_x = cv.split(X, ...)     –  split generator
    next(cv_x)                  –  returns splits only `n_splits` times, then raises  StopIteration  error
    [s for s in cv.split(X, ...)]  – contains all `n_splits` splits 
                                     (pairs of sets of disjoint indices for test and train)
    """

    def __init__(
            self,
            n_splits: int,
            test_size: float | int | None = None,
            train_size: float | int | None = None,
            random_state: int | None = None,
    ):
        """
        n_splits: int,
            number of splits to be generated by any instance of 
            `gen = StratifiedGroupShuffleSplit(...).split(X, y, groups)`
            which is generator.
        test_size: float | int,
            if `int` then number of elements in test part of each indices division
            returned by generator (created as above).
            if float then must be within (0, 1) and means portion of all indices 
            ascribed to test part of division.
        train_size: float | int | None = None,
            the same meaning as for `test_size` but for train part of division;
            used only if `test_size` is None;
        random_state: int | None = None,
            random seed passed to random number generator `np.random`.
        """
        assert test_size or train_size, "One of `test_size` or `train_size` must be not None and non 0."
        self.n_splits = n_splits
        self.test_size = test_size
        self.train_size = train_size  # used only if test_size is None
        self.random_state = random_state
        np.random.seed(random_state)

    def _split_portion(
            self,
            items: list | np.ndarray,
            portion: float,
    ) -> tuple[np.ndarray, np.ndarray]:
        """
        Splits set of `items` into two subsets, say `items_train` and `items_test`,
        with proportions `1 - portion`, `portion` respectively.
        ! It is assumed that elements of `items` are unique.
        If not, the algorithm will return only unique elements of `items`
        and each will belong to only one of the "train" or "test" subset.
        """
        n = len(items)
        items = np.array(items)
        n_test = int(np.ceil(n * portion))  # at least 1
        items_test = np.random.choice(items, size=n_test, replace=False)
        items_train = set(items) - set(items_test)
        return np.array(list(items_train)), items_test

    def _get_test_portion(self, n_obs: int) -> float:
        test_portion: float = -1
        
        if self.test_size and isinstance(self.test_size, int):
            test_portion = self.test_size / n_obs
        elif self.test_size:
            test_portion = self.test_size
        elif self.train_size and isinstance(self.train_size, int):
            test_portion = 1 - self.train_size / n_obs
        elif self.train_size:
            test_portion = 1 - self.train_size
            
        assert test_portion > 0 and test_portion < 1, \
            "Any of `test_size` or `train_size` must be between (0, 1) if float or between (0, n_obs) if int."
        
        return test_portion

    def split(
            self,
            X: pd.DataFrame,
            y: pd.Series,
            groups: pd.Series
    ) -> Generator[tuple[np.ndarray, np.ndarray], None, None]:
        """
        Generator function, i.e. returning Generator
        of `self.n_splits` different splits of data,
        s.t. in each split the same portion of unique groups is maintained
        between train and test parts of a split.

        `X`, `y`, `groups` must all have the same length.
        Returns pair of np.arrays of  numeric indices  (!)
        (those refered to via .iloc method of pd.DataFrame or pd.Series)
        of `X`, `y` and `groups` giving split of these data with proportions `1 - test_size`, `test_size`,
        however wrt unique values of `groups` variable.
        """
        assert len(X) == len(y) == len(groups), "`X`, `y`, `groups` must all have the same length."
        idx = np.arange(len(y))

        test_portion = self._get_test_portion(len(y))

        gu = groups.unique()
        gu_1 = groups[y == 1].unique()
        gu_0 = list(set(gu) - set(gu_1))

        i = 1
        while i <= self.n_splits:
            gu_1_train, gu_1_test = self._split_portion(gu_1, test_portion)
            gu_0_train, gu_0_test = self._split_portion(gu_0, test_portion)

            gu_train = np.r_[gu_1_train, gu_0_train]
            gu_test = np.r_[gu_1_test, gu_0_test]

            idx_train = idx[groups.isin(gu_train)]
            idx_test = idx[groups.isin(gu_test)]

            i += 1

            yield idx_train, idx_test
